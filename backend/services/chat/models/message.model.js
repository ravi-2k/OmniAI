import mongoose from "mongoose";

const codeFileSchema = new mongoose.Schema(
  {
    name: String,
    content: String,
    language: String,
  },
  {
    _id: false,
  },
);

const artifactSchema = new mongoose.Schema(
  {
    id: Number,
    type: String,
    title: String,
    entry: String,
    files: [codeFileSchema],
  },
  {
    _id: false,
  },
);

// Files uploaded by the user (stored in S3, re-signed on demand).
const attachmentSchema = new mongoose.Schema(
  {
    name: String,
    mimeType: String,
    size: Number,
    key: String,
  },
  {
    _id: false,
  },
);

// Files generated by an agent (pdf / ppt / image). Only the S3 key is stored;
// download URLs are signed on demand because they expire.
const generatedFileSchema = new mongoose.Schema(
  {
    name: String,
    type: { type: String, enum: ["pdf", "ppt", "image"] },
    mimeType: String,
    size: Number,
    key: String,
  },
  {
    _id: false,
  },
);

const sourceSchema = new mongoose.Schema(
  {
    title: String,
    url: String,
    snippet: String,
  },
  {
    _id: false,
  },
);

const messageSchema = new mongoose.Schema(
  {
    conversationId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Conversation",
      required: true,
      index: true,
    },
    role: {
      type: String,
      enum: ["user", "assistant"],
      required: true,
    },
    content: {
      type: String,
      default: "",
      maxlength: 200000,
    },
    agent: String,
    images: [String],
    artifacts: [artifactSchema],
    attachments: [attachmentSchema],
    files: [generatedFileSchema],
    sources: [sourceSchema],
    feedback: {
      type: String,
      enum: ["up", "down"],
      default: undefined,
    },
  },
  { timestamps: true },
);

messageSchema.index({ conversationId: 1, createdAt: 1, _id: 1 });

const messageModel = mongoose.model("Message", messageSchema);

export default messageModel;
